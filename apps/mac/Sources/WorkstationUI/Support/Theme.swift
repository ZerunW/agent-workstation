    static let mono = Font.system(size: 12, design: .monospaced)
}

extension NSColor {
    convenience init(hex: UInt32, alpha: CGFloat = 1) {
        self.init(srgbRed: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,
                  blue: CGFloat(hex & 0xFF) / 255, alpha: alpha)
    }

    convenience init(_ c: RGBA) {
        self.init(srgbRed: c.r / 255, green: c.g / 255, blue: c.b / 255, alpha: c.a)
    }
}

/// Small status dot (sync phase).
struct Dot: View {
    var color: Color
    var size: CGFloat = 7
    var body: some View { Circle().fill(color).frame(width: size, height: size) }
}

/// The app glyph (same drawing as the icon generated by make-app.sh).
struct AppGlyph: View {
    var body: some View {
        ZStack {
            RoundedRectangle(cornerRadius: 10, style: .continuous)
                .fill(LinearGradient(colors: [Color(nsColor: NSColor(hex: 0x2A9D8F)), Color(nsColor: NSColor(hex: 0x0F766E))], startPoint: .top, endPoint: .bottom))
            Image(systemName: "chevron.left.forwardslash.chevron.right").font(.system(size: 18, weight: .bold)).foregroundStyle(.white)
        }
    }
}
