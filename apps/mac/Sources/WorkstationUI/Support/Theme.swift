/// The few colours the remaining native screens need. Everything else uses system colours so
/// Settings, the first-run sheet and the folders window look like standard macOS panels; the
/// teal accent matches the web app.
public enum Theme {
    static func dynamic(light: UInt32, dark: UInt32) -> Color {
        Color(nsColor: NSColor(name: nil) { appearance in
            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua, .vibrantDark, .vibrantLight]).map { $0 == .darkAqua || $0 == .vibrantDark } ?? false
            return NSColor(hex: isDark ? dark : light)
        })
    }

    public static let accent = dynamic(light: 0x0F766E, dark: 0x2A9D8F)
    public static let success = dynamic(light: 0x3F8F5B, dark: 0x5DB57A)
    public static let warning = dynamic(light: 0xB7791F, dark: 0xE0A93B)
    public static let danger = dynamic(light: 0xC0392B, dark: 0xE5674F)
    /// Window background before the page has painted (close to the web app's `--bg`).
    public static let pageBackground = NSColor(name: nil) { appearance in
        let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
        return NSColor(hex: isDark ? 0x1B1E22 : 0xF7F8FA)
    }
}

/// The web app's colour tokens (`packages/web/src/index.css`), light / dark, so native review
/// screens look like the web app's diff view.
enum Web {
    static func c(_ light: UInt32, _ la: CGFloat = 1, _ dark: UInt32, _ da: CGFloat = 1) -> Color {
        Color(nsColor: NSColor(name: nil) { appearance in
            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            return NSColor(hex: isDark ? dark : light, alpha: isDark ? da : la)
        })
    }
    static let bg = c(0xF7F8FA, 1, 0x1B1E22)
    static let sidebar = c(0xEEF0F3, 1, 0x15181B)
    static let surface = c(0xFFFFFF, 1, 0x24282D)
    static let hover = c(0x16191D, 0.055, 0xF0F4F8, 0.07)
    static let active = c(0x16191D, 0.10, 0xF0F4F8, 0.12)
    static let fg = c(0x16191D, 1, 0xEEF1F4)
    static let muted = c(0x5B6270, 1, 0xA9B0BA)
    static let subtle = c(0x8A919C, 1, 0x7D8590)
    static let line = c(0x16191D, 0.11, 0xF0F4F8, 0.11)
    static let accent = c(0x0F766E, 1, 0x2A9D8F)
    static let ok = c(0x2F8456, 1, 0x5FC08A)
    static let warn = c(0xA96A0C, 1, 0xE0A54A)
    static let warnSoft = c(0xD9941C, 0.15, 0xE0A54A, 0.16)
    static let danger = c(0xC23B2B, 1, 0xEF7A6B)
