export type I18nKey = keyof typeof en;
type Messages = Record<I18nKey, string>;

const catalogs: Record<string, Messages> = { en: en as unknown as Messages };
let locale = "en";

export function setLocale(next: string): void {
  if (catalogs[next]) locale = next;
}

/** Register another language (partial catalogs fall back to English per key). */
export function registerLocale(code: string, messages: Partial<Messages>): void {
  catalogs[code] = { ...(en as unknown as Messages), ...messages };
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const raw = catalogs[locale]?.[key] ?? (en as unknown as Messages)[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}
